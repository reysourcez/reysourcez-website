function downloadPNG() {
  if (!lastEncoded) return;
  const exportPx = Number(document.getElementById('qr-export-size').value) || PNG_EXPORT_PX_DEFAULT;
  const quietZone = Number(document.getElementById('qr-quiet-zone').value) || QUIET_ZONE_DEFAULT;
  const plan = buildRenderPlan(lastEncoded.matrix, lastEncoded.size, currentStyleOptions());
  const pxPerModule = exportPx / (lastEncoded.size + quietZone * 2);
  const offscreen = document.createElement('canvas');
  renderPlanToCanvas(offscreen, plan, pxPerModule, quietZone);
  if (logoImageEl) {
    const shape = document.querySelector('[name="qr-logo-shape"]:checked').value;
    const sizePct = Number(document.getElementById('qr-logo-size').value) || LOGO_SIZE_DEFAULT_PCT;
    drawLogoOverlay(offscreen, logoImageEl, sizePct, shape);
  }
  downloadDataUrl('qr-code.png', offscreen.toDataURL('image/png'));
}

function downloadSVG() {
  if (!lastEncoded) return;
  const quietZone = Number(document.getElementById('qr-quiet-zone').value) || QUIET_ZONE_DEFAULT;
  const plan = buildRenderPlan(lastEncoded.matrix, lastEncoded.size, currentStyleOptions());
  let svg = renderPlanToSVGString(plan, 10, quietZone); // 10px/module in SVG user-units — it's vector, so this only sets the viewBox scale, not the print resolution
  if (logoImageEl) {
    // Embed the logo as a base64 <image> so the SVG stays fully
    // self-contained (matches this site's "no external references"
    // rule for exported assets, same reasoning as inlined fonts/CSS
    // elsewhere on the site).
    const total = (lastEncoded.size + quietZone * 2) * 10;
    const shape = document.querySelector('[name="qr-logo-shape"]:checked').value;
    const sizePct = Number(document.getElementById('qr-logo-size').value) || LOGO_SIZE_DEFAULT_PCT;
    const logoPx = total * (sizePct / 100);
    const plateInset = logoPx * 0.14;
    const plateSize = logoPx + plateInset * 2;
    const cx = total / 2, cy = total / 2;
    let plateShape;
    if (shape === 'circle') plateShape = '<circle cx="' + cx + '" cy="' + cy + '" r="' + (plateSize / 2) + '" fill="#fff"/>';
    else plateShape = '<path d="' + roundedRectPathPx(cx - plateSize / 2, cy - plateSize / 2, plateSize, plateSize, shape === 'rounded' ? plateSize * 0.18 : 0) + '" fill="#fff"/>';
    const logoTag = '<image href="' + document.getElementById('qr-logo-preview').src + '" x="' + (cx - logoPx / 2) + '" y="' + (cy - logoPx / 2) + '" width="' + logoPx + '" height="' + logoPx + '" preserveAspectRatio="xMidYMid meet"/>';
    svg = svg.replace('</svg>', plateShape + logoTag + '</svg>');
  }
  downloadDataUrl('qr-code.svg', 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg));
}

