function recalculate() {
  const text = gatherContentPayload();
  const statusEl = document.getElementById('qr-status');
  const hasLogo = !!logoImageEl;
  let eccLevel = document.getElementById('qr-ecc-level').value;
  if (hasLogo) eccLevel = LOGO_FORCE_ECC;

  if (!text) {
    document.getElementById('qr-preview-wrap').classList.add('is-empty');
    statusEl.textContent = 'Fill in the fields above to generate your code.';
    statusEl.classList.remove('is-error');
    document.querySelectorAll('.qr-download-btn').forEach(function (b) { b.disabled = true; });
    lastEncoded = null;
    return;
  }

  let encoded;
  try {
    encoded = QRCreatorEngine.encode(text, { eccLevel: eccLevel, boostEcl: !hasLogo });
  } catch (err) {
    document.getElementById('qr-preview-wrap').classList.add('is-empty');
    statusEl.textContent = err.message || 'Could not generate a code for this content.';
    statusEl.classList.add('is-error');
    document.querySelectorAll('.qr-download-btn').forEach(function (b) { b.disabled = true; });
    lastEncoded = null;
    return;
  }
  lastEncoded = encoded;
  document.getElementById('qr-preview-wrap').classList.remove('is-empty');
  document.querySelectorAll('.qr-download-btn').forEach(function (b) { b.disabled = false; });

  const quietZone = Number(document.getElementById('qr-quiet-zone').value) || QUIET_ZONE_DEFAULT;
  const plan = buildRenderPlan(encoded.matrix, encoded.size, currentStyleOptions());
  const pxPerModule = PREVIEW_PX / (encoded.size + quietZone * 2);
  const canvas = document.getElementById('qr-preview-canvas');
  renderPlanToCanvas(canvas, plan, pxPerModule, quietZone);

  if (hasLogo) {
    const shape = document.querySelector('[name="qr-logo-shape"]:checked').value;
    const sizePct = Number(document.getElementById('qr-logo-size').value) || LOGO_SIZE_DEFAULT_PCT;
    drawLogoOverlay(canvas, logoImageEl, sizePct, shape);
  }

  statusEl.classList.remove('is-error');
  statusEl.textContent = 'Version ' + encoded.version + ' · ' + encoded.size + '\u00d7' + encoded.size + ' modules · '
    + 'Error correction ' + encoded.level + (hasLogo ? ' (raised automatically for the logo)' : '') + '.';
}

/* ================= LOGO UPLOAD ================= */

function handleLogoFile(file) {
  if (!file) return;
  const reader = new FileReader();
  reader.onload = function () {
    const img = new Image();
    img.onload = function () {
      logoImageEl = img;
      document.getElementById('qr-logo-controls').hidden = false;
      document.getElementById('qr-logo-preview').src = reader.result;
      document.getElementById('qr-logo-preview').hidden = false;
      document.getElementById('qr-ecc-level').value = LOGO_FORCE_ECC;
      document.getElementById('qr-ecc-level').disabled = true;
      document.getElementById('qr-ecc-forced-note').hidden = false;
      recalculate();
    };
    img.onerror = function () { document.getElementById('qr-logo-status').textContent = 'Could not read that image — try a different file.'; };
    img.src = reader.result;
  };
  reader.readAsDataURL(file);
}
function removeLogo() {
  logoImageEl = null;
  document.getElementById('qr-logo-controls').hidden = true;
  document.getElementById('qr-logo-preview').hidden = true;
  document.getElementById('qr-logo-input').value = '';
  document.getElementById('qr-ecc-level').disabled = false;
  document.getElementById('qr-ecc-forced-note').hidden = true;
  recalculate();
}

