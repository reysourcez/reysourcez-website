const CONTENT_TYPES = ['text', 'wifi', 'vcard', 'email', 'phone'];
let activeContentType = 'text';
let logoImageEl = null; // the loaded <img>, once a logo's been chosen

function gatherContentPayload() {
  switch (activeContentType) {
    case 'wifi':
      return buildWifiPayload({
        ssid: val('qr-wifi-ssid'), password: val('qr-wifi-password'),
        encryption: val('qr-wifi-encryption'), hidden: document.getElementById('qr-wifi-hidden').checked,
      });
    case 'vcard':
      return buildVCardPayload({
        firstName: val('qr-vcard-first'), lastName: val('qr-vcard-last'), org: val('qr-vcard-org'),
        title: val('qr-vcard-title'), phone: val('qr-vcard-phone'), email: val('qr-vcard-email'),
        url: val('qr-vcard-url'), address: val('qr-vcard-address'),
      });
    case 'email':
      return buildMailtoPayload({ to: val('qr-email-to'), subject: val('qr-email-subject'), body: val('qr-email-body') });
    case 'phone':
      return val('qr-phone-mode') === 'sms'
        ? buildSmsPayload({ number: val('qr-phone-number'), body: val('qr-phone-sms-body') })
        : buildTelPayload({ number: val('qr-phone-number') });
    default:
      return val('qr-text-input');
  }
}
function val(id) { var el = document.getElementById(id); return el ? el.value.trim() : ''; }

function switchContentType(type) {
  activeContentType = type;
  document.querySelectorAll('[data-content-type]').forEach(function (t) { t.classList.toggle('is-active', t.dataset.contentType === type); });
  document.querySelectorAll('[data-content-panel]').forEach(function (p) { p.hidden = p.dataset.contentPanel !== type; });
  updatePhoneModeVisibility();
  updateWifiPasswordVisibility();
  recalculate();
}

