/* ================= CONTENT-TYPE PAYLOAD BUILDERS =================
   WIFI: syntax matches the de-facto standard both Android and iOS
   camera apps parse (documented by the ZXing project). vCard uses
   3.0 specifically, not 4.0 — 3.0 is what scans reliably into both
   iOS and Android's native "add contact" flow; 4.0 has real parser
   gaps on older devices for QR-scanned cards specifically. Both
   verified against current documentation while building this, not
   assumed from memory. */

function escapeFieldGeneric(s, extra) {
  var out = String(s == null ? '' : s).replace(/\\/g, '\\\\');
  (extra || [';', ',', ':']).forEach(function (ch) { out = out.split(ch).join('\\' + ch); });
  return out;
}

function buildWifiPayload(f) {
  f = f || {};
  var type = f.encryption || 'WPA'; // 'WPA' | 'WEP' | 'nopass'
  var parts = ['WIFI:T:' + type + ';S:' + escapeFieldGeneric(f.ssid)];
  if (type !== 'nopass') parts.push('P:' + escapeFieldGeneric(f.password));
  if (f.hidden) parts.push('H:true');
  return parts.join(';') + ';;';
}

function buildVCardPayload(f) {
  f = f || {};
  var esc = function (s) { return escapeFieldGeneric(s, [';', ',']).replace(/\n/g, '\\n'); };
  var lines = ['BEGIN:VCARD', 'VERSION:3.0'];
  lines.push('N:' + esc(f.lastName) + ';' + esc(f.firstName) + ';;;');
  var fn = [f.firstName, f.lastName].filter(Boolean).join(' ').trim() || f.org || '';
  lines.push('FN:' + esc(fn));
  if (f.org) lines.push('ORG:' + esc(f.org));
  if (f.title) lines.push('TITLE:' + esc(f.title));
  if (f.phone) lines.push('TEL;TYPE=CELL,VOICE:' + f.phone);
  if (f.email) lines.push('EMAIL;TYPE=INTERNET:' + f.email);
  if (f.url) lines.push('URL:' + f.url);
  if (f.address) lines.push('ADR;TYPE=WORK:;;' + esc(f.address) + ';;;;');
  if (f.note) lines.push('NOTE:' + esc(f.note));
  lines.push('END:VCARD');
  return lines.join('\r\n');
}

function buildMailtoPayload(f) {
  f = f || {};
  var params = [];
  if (f.subject) params.push('subject=' + encodeURIComponent(f.subject));
  if (f.body) params.push('body=' + encodeURIComponent(f.body));
  return 'mailto:' + (f.to || '') + (params.length ? '?' + params.join('&') : '');
}
function buildTelPayload(f) { return 'tel:' + String((f && f.number) || '').replace(/[^\d+]/g, ''); }
function buildSmsPayload(f) {
  f = f || {};
  var n = String(f.number || '').replace(/[^\d+]/g, '');
  return 'sms:' + n + (f.body ? '?body=' + encodeURIComponent(f.body) : '');
}

/* ================= MODULE CLASSIFICATION + RENDER PLAN =================
   Shared, resolution-independent shape geometry — see this file's own
   header comment for why the same plan drives canvas, SVG, and the
   live preview identically. Coordinates throughout are in MODULE
   units (0..size); renderPlanToCanvas/renderPlanToSVGString are the
   only two places pixel scale or quiet-zone offset ever get applied. */

function classifyModule(x, y, size) {
  var boxes = [[0, 0], [size - 7, 0], [0, size - 7]];
  for (var i = 0; i < boxes.length; i++) {
    var dx = x - boxes[i][0], dy = y - boxes[i][1];
    if (dx >= 0 && dx <= 6 && dy >= 0 && dy <= 6) {
      if (dx === 0 || dx === 6 || dy === 0 || dy === 6) return 'finder-frame';
      if (dx >= 2 && dx <= 4 && dy >= 2 && dy <= 4) return 'finder-ball';
      return 'finder-gap'; // the light ring between frame and ball; never dark, never drawn
    }
  }
  return 'body';
}

function roundedRectPath(x, y, w, h, tl, tr, br, bl) {
  tl = Math.max(0, Math.min(tl, w / 2, h / 2));
  tr = Math.max(0, Math.min(tr, w / 2, h / 2));
  br = Math.max(0, Math.min(br, w / 2, h / 2));
  bl = Math.max(0, Math.min(bl, w / 2, h / 2));
  return 'M' + (x + tl) + ',' + y
    + ' L' + (x + w - tr) + ',' + y + ' A' + tr + ',' + tr + ' 0 0 1 ' + (x + w) + ',' + (y + tr)
    + ' L' + (x + w) + ',' + (y + h - br) + ' A' + br + ',' + br + ' 0 0 1 ' + (x + w - br) + ',' + (y + h)
    + ' L' + (x + bl) + ',' + (y + h) + ' A' + bl + ',' + bl + ' 0 0 1 ' + x + ',' + (y + h - bl)
    + ' L' + x + ',' + (y + tl) + ' A' + tl + ',' + tl + ' 0 0 1 ' + (x + tl) + ',' + y + ' Z';
}

function bodyDarkNeighbor(matrix, size, x, y, dx, dy) {
  var nx = x + dx, ny = y + dy;
  if (nx < 0 || ny < 0 || nx >= size || ny >= size) return false;
  if (!matrix[ny][nx]) return false;
  return classifyModule(nx, ny, size) === 'body';
}

// options: { bodyStyle: 'square'|'dots'|'rounded', dotScale, roundedScale,
//   eyeFrameStyle, eyeBallStyle: 'square'|'rounded'|'circle',
//   fg, bg, eyeFrameColor, eyeBallColor }
// dotScale 0.46 and the eye-ring radii below were the exact values
// empirically scan-tested (see this file's header) — safe to nudge
// slightly but treat as verified defaults, not arbitrary numbers.
function buildRenderPlan(matrix, size, options) {
  var o = options || {};
  var bodyStyle = o.bodyStyle || 'square';
  var dotScale = o.dotScale != null ? o.dotScale : 0.46;
  var roundedScale = o.roundedScale != null ? o.roundedScale : 0.3;
  var eyeFrameStyle = o.eyeFrameStyle || 'square';
  var eyeBallStyle = o.eyeBallStyle || 'square';
  var fg = o.fg || DEFAULT_FG;
  var bg = o.bg || DEFAULT_BG;
  var eyeFrameColor = o.eyeFrameColor || fg;
  var eyeBallColor = o.eyeBallColor || fg;

  var shapes = [];
  var drawnEyeBoxes = {};

  function addEyeShapes(originX, originY) {
    var key = originX + ',' + originY;
    if (drawnEyeBoxes[key]) return;
    drawnEyeBoxes[key] = true;
    // Draw outer solid, then a background-colored "hole" on top --
    // valid because this tool only offers flat solid colors; would
    // need revisiting if a gradient/pattern fill is ever added (see
    // QR_CREATOR_NOTES.md's KIV list).
    if (eyeFrameStyle === 'circle') {
      shapes.push({ type: 'circle', cx: originX + 3.5, cy: originY + 3.5, r: 3.5, fill: eyeFrameColor });
      shapes.push({ type: 'circle', cx: originX + 3.5, cy: originY + 3.5, r: 2.5, fill: bg });
    } else if (eyeFrameStyle === 'rounded') {
      shapes.push({ type: 'path', d: roundedRectPath(originX, originY, 7, 7, 1.8, 1.8, 1.8, 1.8), fill: eyeFrameColor });
      shapes.push({ type: 'path', d: roundedRectPath(originX + 1, originY + 1, 5, 5, 1.2, 1.2, 1.2, 1.2), fill: bg });
    } else {
      shapes.push({ type: 'rect', x: originX, y: originY, w: 7, h: 7, fill: eyeFrameColor });
      shapes.push({ type: 'rect', x: originX + 1, y: originY + 1, w: 5, h: 5, fill: bg });
    }
    if (eyeBallStyle === 'circle') {
      shapes.push({ type: 'circle', cx: originX + 3.5, cy: originY + 3.5, r: 1.55, fill: eyeBallColor });
    } else if (eyeBallStyle === 'rounded') {
      shapes.push({ type: 'path', d: roundedRectPath(originX + 2, originY + 2, 3, 3, 0.9, 0.9, 0.9, 0.9), fill: eyeBallColor });
    } else {
      shapes.push({ type: 'rect', x: originX + 2, y: originY + 2, w: 3, h: 3, fill: eyeBallColor });
    }
  }

  for (var y = 0; y < size; y++) {
    for (var x = 0; x < size; x++) {
      if (!matrix[y][x]) continue;
      var cls = classifyModule(x, y, size);
      if (cls === 'finder-frame' || cls === 'finder-ball') {
        addEyeShapes(x < 7 ? 0 : size - 7, y < 7 ? 0 : size - 7);
        continue;
      }
      if (bodyStyle === 'dots') {
        shapes.push({ type: 'circle', cx: x + 0.5, cy: y + 0.5, r: dotScale, fill: fg });
      } else if (bodyStyle === 'rounded') {
        var up = bodyDarkNeighbor(matrix, size, x, y, 0, -1);
        var down = bodyDarkNeighbor(matrix, size, x, y, 0, 1);
        var left = bodyDarkNeighbor(matrix, size, x, y, -1, 0);
        var right = bodyDarkNeighbor(matrix, size, x, y, 1, 0);
        var r = roundedScale;
        shapes.push({ type: 'path', d: roundedRectPath(x, y, 1, 1, (up || left) ? 0 : r, (up || right) ? 0 : r, (down || right) ? 0 : r, (down || left) ? 0 : r), fill: fg });
      } else {
        shapes.push({ type: 'rect', x: x, y: y, w: 1, h: 1, fill: fg });
      }
    }
  }
  return { size: size, bg: bg, shapes: shapes };
}

/* ================= CANVAS RENDERING ================= */

function renderPlanToCanvas(canvas, plan, pxPerModule, quietZoneModules) {
  var totalPx = (plan.size + quietZoneModules * 2) * pxPerModule;
  canvas.width = totalPx;
  canvas.height = totalPx;
  var ctx = canvas.getContext('2d');
  ctx.fillStyle = plan.bg;
  ctx.fillRect(0, 0, totalPx, totalPx);
  var offset = quietZoneModules * pxPerModule;

  plan.shapes.forEach(function (s) {
    ctx.fillStyle = s.fill;
    if (s.type === 'rect') {
      ctx.fillRect(offset + s.x * pxPerModule, offset + s.y * pxPerModule, s.w * pxPerModule, s.h * pxPerModule);
    } else if (s.type === 'circle') {
      ctx.beginPath();
      ctx.arc(offset + s.cx * pxPerModule, offset + s.cy * pxPerModule, s.r * pxPerModule, 0, Math.PI * 2);
      ctx.fill();
    } else if (s.type === 'path') {
      ctx.save();
      ctx.translate(offset, offset);
      ctx.scale(pxPerModule, pxPerModule);
      ctx.fill(new Path2D(s.d));
      ctx.restore();
    }
  });
  return ctx;
}

function renderPlanToSVGString(plan, pxPerModule, quietZoneModules) {
  var totalPx = (plan.size + quietZoneModules * 2) * pxPerModule;
  var offset = quietZoneModules * pxPerModule;
  var body = plan.shapes.map(function (s) {
    if (s.type === 'rect') {
      return '<rect x="' + (offset + s.x * pxPerModule).toFixed(2) + '" y="' + (offset + s.y * pxPerModule).toFixed(2)
        + '" width="' + (s.w * pxPerModule).toFixed(2) + '" height="' + (s.h * pxPerModule).toFixed(2) + '" fill="' + s.fill + '"/>';
    }
    if (s.type === 'circle') {
      return '<circle cx="' + (offset + s.cx * pxPerModule).toFixed(2) + '" cy="' + (offset + s.cy * pxPerModule).toFixed(2)
        + '" r="' + (s.r * pxPerModule).toFixed(2) + '" fill="' + s.fill + '"/>';
    }
    // path: translate+scale via a <g transform>, one per shape is fine at these counts
    return '<g transform="translate(' + offset + ',' + offset + ') scale(' + pxPerModule + ')"><path d="' + s.d + '" fill="' + s.fill + '"/></g>';
  }).join('');
  return '<svg xmlns="http://www.w3.org/2000/svg" width="' + totalPx + '" height="' + totalPx + '" viewBox="0 0 ' + totalPx + ' ' + totalPx + '">'
    + '<rect width="' + totalPx + '" height="' + totalPx + '" fill="' + plan.bg + '"/>' + body + '</svg>';
}

/* ================= LOGO OVERLAY =================
   Drawn on top of the finished canvas — never touches the matrix or
   the encoder. Standard, proven approach (what every consumer "QR +
   logo" generator does): encode at high error correction, then
   visually cover the center. Width-based sizing keeps this safe by
   construction — area scales with the SQUARE of the width fraction,
   so even a generous-looking 32%-wide logo only covers ~10% of the
   matrix area, comfortably under level H's 30% recovery budget, with
   the backing plate included. */

function drawLogoOverlay(canvas, logoImg, sizePct, shape) {
  var ctx = canvas.getContext('2d');
  var total = canvas.width;
  var logoPx = total * (sizePct / 100);
  var plateInset = logoPx * 0.14; // backing plate slightly larger than the logo itself
  var plateSize = logoPx + plateInset * 2;
  var cx = total / 2, cy = total / 2;

  ctx.save();
  ctx.fillStyle = '#FFFFFF';
  if (shape === 'circle') {
    ctx.beginPath();
    ctx.arc(cx, cy, plateSize / 2, 0, Math.PI * 2);
    ctx.fill();
  } else {
    var r = shape === 'rounded' ? plateSize * 0.18 : 0;
    ctx.beginPath();
    ctx.fill(new Path2D(roundedRectPathPx(cx - plateSize / 2, cy - plateSize / 2, plateSize, plateSize, r)));
  }
  ctx.restore();

  var drawW = logoPx, drawH = logoPx;
  if (logoImg.naturalWidth && logoImg.naturalHeight) {
    var ratio = logoImg.naturalWidth / logoImg.naturalHeight;
    if (ratio > 1) drawH = logoPx / ratio; else drawW = logoPx * ratio;
  }
  ctx.drawImage(logoImg, cx - drawW / 2, cy - drawH / 2, drawW, drawH);
}

// Pixel-space rounded-rect path (separate from the module-space one
// above — logo placement works directly in canvas pixels, not
// modules, since it's independent of the QR grid).
function roundedRectPathPx(x, y, w, h, r) {
  r = Math.max(0, Math.min(r, w / 2, h / 2));
  return 'M' + (x + r) + ',' + y + ' L' + (x + w - r) + ',' + y + ' A' + r + ',' + r + ' 0 0 1 ' + (x + w) + ',' + (y + r)
    + ' L' + (x + w) + ',' + (y + h - r) + ' A' + r + ',' + r + ' 0 0 1 ' + (x + w - r) + ',' + (y + h)
    + ' L' + (x + r) + ',' + (y + h) + ' A' + r + ',' + r + ' 0 0 1 ' + x + ',' + (y + h - r)
    + ' L' + x + ',' + (y + r) + ' A' + r + ',' + r + ' 0 0 1 ' + (x + r) + ',' + y + ' Z';
}

